export const DICT: Record<Language, Record<Key, string>> = { en: EN, de: DE };
export const LANGUAGES: Language[] = ["en", "de"];

let current: Language = "en";
const CACHE_KEY = "exam-tab-lang"; // read synchronously at start-up, so the page doesn't flash English first

export const getLang = (): Language => current;

/** Switches the language (and <html lang>), and remembers it for the next start-up. */
export function setLang(lang: Language | undefined): void {
  current = lang === "de" ? "de" : "en";
  if (typeof document !== "undefined") document.documentElement.lang = current;
  try {
    localStorage.setItem(CACHE_KEY, current);
  } catch {
    // workers and private mode: fine, settings still hold the language
  }
}

/** The language used last time, before settings have loaded. */
export function cachedLang(): Language {
  try {
    return localStorage.getItem(CACHE_KEY) === "de" ? "de" : "en";
  } catch {
    return "en";
  }
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return DICT[current][key].replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

/** Counted text: picks "<base>.one" or "<base>.other" and fills {n}. */
export function tn(base: string, n: number, vars: Record<string, string | number> = {}): string {
  return t(`${base}.${n === 1 ? "one" : "other"}` as Key, { n, ...vars });
}

const ATTRS = ["aria-label", "placeholder", "title"] as const;

/** Fills every [data-i18n] text and [data-i18n-<attr>] attribute below `root`. */
export function applyI18n(root: ParentNode = document): void {
  for (const node of Array.from(root.querySelectorAll<HTMLElement>("[data-i18n]"))) node.textContent = t(node.dataset.i18n as Key);
  for (const attr of ATTRS)
    for (const node of Array.from(root.querySelectorAll<HTMLElement>(`[data-i18n-${attr}]`)))
      node.setAttribute(attr, t(node.getAttribute(`data-i18n-${attr}`) as Key));
  const title = document.querySelector<HTMLElement>("[data-i18n-doc-title]");
  if (title) document.title = t(title.dataset.i18nDocTitle as Key);
}

export const isKey = (k: string): k is Key => k in EN;
